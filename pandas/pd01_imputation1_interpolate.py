'''
결측치 처리
1. 삭제 - 행 또는 열
2. 임의의 값 채워넣기
    - 0: fillna
    - 평균: mean (이상치에 유의할 것)
    - 중위: median
    - 앞의 값: ffill
    - 뒤의 값: bfill
    - 특정 값: 조건 보고 넣기
    - 최빈값
3. interpolate - 보간(알려진 데이터 점 집합 범위 내에 새 데이터 점을 추가하는 기법)
4. 모델: .predict(값을 예측해서 채우고) > (그 뒤엔 전혀 다른 모델 사용)
5. Boosting(Tree) 계열 모델: 통상 결측치, 이상치에 대해 영향을 덜 받음
6. 스케일링(Robust): 이상치에 자유로움
'''
import pandas as pd
import numpy as np

dates = [
    '11/11/2026', '11/12/2026', '11/13/2026',
    '11/14/2026', '11/15/2026', '11/16/2026',
    '11/17/2026', '11/18/2026', '11/19/2026',
]

dates = pd.to_datetime(dates)
print(dates)
'''
DatetimeIndex(['2026-11-11', '2026-11-12', '2026-11-13', '2026-11-14',
               '2026-11-15', '2026-11-16', '2026-11-17', '2026-11-18',
               '2026-11-19'],
              dtype='datetime64[us]', freq=None)
'''
print("====================================")
# ts = pd.Series([0, 2, np.nan, np.nan, 8, 10, np.nan, 14, 16], index=dates)
ts = pd.Series([0, 2, np.nan, np.nan, 8, 10, np.nan, 14, np.nan], index=dates)
print(ts)
'''
2026-11-11     0.0
2026-11-12     2.0
2026-11-13     NaN
2026-11-14     NaN
2026-11-15     8.0
2026-11-16    10.0
2026-11-17     NaN
2026-11-18    14.0
2026-11-19     NaN
dtype: float64
>> 여기 있는 YYYY-MM-DD는 날짜가 아닌 인덱스
'''
print("====================================")
ts = ts.interpolate()
print(ts)
'''
2026-11-11     0.0
2026-11-12     2.0
2026-11-13     4.0
2026-11-14     6.0
2026-11-15     8.0
2026-11-16    10.0
2026-11-17    12.0
2026-11-18    14.0
2026-11-19    14.0
dtype: float64
'''

# 중간값들은 linear로 채워짐
# 마지막 값이 결측치일 경우 ffill로 채워짐
# 첫 번째 값이 결측치일 경우 채워지지 않음